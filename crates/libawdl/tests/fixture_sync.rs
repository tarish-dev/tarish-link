//! Real Synchronization Parameters (tag 4) and Channel Sequence (tag 18) values.
//!
//! Extracted with `awdl tlv <capture> <tag> [mac]`, not transcribed by hand — a fixture
//! copied out of a hex dump by eye is how a byte-equality test ends up certifying the
//! wrong bytes, at which point it is worse than no test.
//!
//! Three senders on purpose. They disagree about almost everything a builder could get
//! wrong: the channel-sequence encoding (Legacy vs OpClass), whether slot 0 carries an
//! association, whether the schedule is sparse or full, and whether the two bytes after
//! the sequence are zero.
